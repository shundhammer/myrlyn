#include <QMessageBox>

#include "Exception.h"
#include "Logger.h"
#include "MainWindow.h"
#include "utf8.h"
#include "YQi18n.h"
#include "ExpiredGpgKeyDialog.h"


ExpiredGpgKeyDialog::ExpiredGpgKeyDialog( const zypp::PublicKey & key,
                                                QWidget *         parent   )
    : QDialog( parent ? parent : MainWindow::instance() )
    , _ui( new Ui::ExpiredGpgKeyDialog ) // Use the Qt designer .ui form (XML)
{
    CHECK_NEW( _ui );
    _ui->setupUi( this ); // Actually create the widgets from the .ui form


    // See ui_expired-gpg-key-dialog.h for the widget names.
    //
    // That header is generated by Qt's uic (user interface compiler)
    // from the XML .ui file created with Qt designer.
    //
    // Take care in Qt designer to give each widget a meaningful name in the
    // widget tree at the top right: They are also the member variable names
    // for the _ui object.

    setText( _ui->fingerprint, zypp::str::gapify( key.fingerprint(), 4 ) );
    setText( _ui->keyName,     key.name()     );
    setText( _ui->keyId,       key.id()       );
    setText( _ui->keyCreated,  key.created().form( "%F" ) ); // ISO date ("2025-01-15"); see 'man strftime'
    setText( _ui->keyExpires,  key.expires().form( "%F" ) );

    qApp->setOverrideCursor( Qt::ArrowCursor );

    connect( _ui->deleteKeyButton, SIGNAL ( clicked() ),
             this,                 SLOT   ( accept()  ) );

    connect( _ui->cancelButton,    SIGNAL( clicked() ),
             this,                 SLOT  ( reject()  ) );

    logDebug() << "Asking user to delete the expired GPG key " << key.name() << endl;
}


ExpiredGpgKeyDialog::~ExpiredGpgKeyDialog()
{
    delete _ui;
}


void ExpiredGpgKeyDialog::accept()
{
    logResult( "Accepting" );

    qApp->restoreOverrideCursor();
    QDialog::accept();
}


void ExpiredGpgKeyDialog::reject()
{
    logResult( "Rejecting" );

    qApp->restoreOverrideCursor();
    QDialog::reject();
}


void ExpiredGpgKeyDialog::logResult( const QString & result )
{
    logInfo() << result << " deleting expired GPG key " << _ui->keyName->text() << endl;
}


void ExpiredGpgKeyDialog::setText( QLabel * label, const std::string & text )
{
    label->setText( fromUTF8( text ) );
}
